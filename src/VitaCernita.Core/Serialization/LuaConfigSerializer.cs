    private static string FormatSizeCondition(SizeCondition sc)
    {
        string escaped = EscapeLuaString(sc.Size);
        return sc.Operator.ToLowerInvariant() switch
        {
            "larger" or "larger_than" => $"larger(\"{escaped}\")",
            "smaller" or "smaller_than" => $"smaller(\"{escaped}\")",
