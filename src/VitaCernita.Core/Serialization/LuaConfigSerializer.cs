    }

    private static string FormatDateCondition(DateCondition dc)
    {
        string d = dc.Date.ToString("yyyy/MM/dd", CultureInfo.InvariantCulture);
        return dc.Operator.ToLowerInvariant() switch
        {
            "after" => $"After(\"{d}\")",
            "before" => $"Before(\"{d}\")",
            "older" => $"Older(\"{d}\")",
            "newer" => $"Newer(\"{d}\")",
            _ => $"{dc.Operator}(\"{d}\")"
        };
    }

    private static string FormatDurationCondition(DurationCondition durc)
    {
        string escaped = EscapeLuaString(durc.Duration);
        return durc.Operator.ToLowerInvariant() switch
        {
            "older_than" => $"older_than(\"{escaped}\")",
            "newer_than" => $"newer_than(\"{escaped}\")",
            _ => $"{durc.Operator}(\"{escaped}\")"
        };
    }

    private static string FormatAndCondition(AndCondition ac, int indentLevel, LuaSerializerOptions options)
    {
        if (ac.Conditions.Count == 0) return string.Empty;
        if (ac.Conditions.Count == 1) return FormatCondition(ac.Conditions[0], indentLevel, options);

        var childIndent = Indent(indentLevel + 1, options);
        var parentIndent = Indent(indentLevel, options);
        var childStrings = ac.Conditions.Select(c => $"{childIndent}{FormatCondition(c, indentLevel + 1, options)}");

        return $"And(\n{string.Join(",\n", childStrings)}\n{parentIndent})";
    }

    private static string FormatOrCondition(OrCondition oc, int indentLevel, LuaSerializerOptions options)
    {
        if (oc.Conditions.Count == 0) return string.Empty;
        if (oc.Conditions.Count == 1) return FormatCondition(oc.Conditions[0], indentLevel, options);

        var childIndent = Indent(indentLevel + 1, options);
        var parentIndent = Indent(indentLevel, options);
        var childStrings = oc.Conditions.Select(c => $"{childIndent}{FormatCondition(c, indentLevel + 1, options)}");

        return $"Or(\n{string.Join(",\n", childStrings)}\n{parentIndent})";
    }

    public static string FormatAction(
        GmailAction action,
        LuaSerializerOptions options,
        IEnumerable<GmailLabel>? knownLabels = null)
    {
        var effectiveLabels = knownLabels ?? options.KnownLabels;
        var idToName = effectiveLabels?
            .Where(l => !string.IsNullOrEmpty(l.Id) && !string.IsNullOrEmpty(l.Name))
            .ToDictionary(l => l.Id!, l => l.Name, StringComparer.OrdinalIgnoreCase);

        var items = new List<string>();

        // Prefer concise DSL commands for system label additions/removals
        if (action.IsArchive) items.Add("archive");
        if (action.IsMarkUnread) items.Add("mark_read");
        if (action.IsStarred) items.Add("star");
        if (action.IsDelete) items.Add("delete");
        if (action.IsImportant) items.Add("mark_important");

        if (action.Category != null)
        {
            string cat = FormatCategoryAction(action.Category);
            items.Add($"add_category(\"{cat}\")");
        }

        // Custom labels to add: resolve ID to human-readable Name if known
        foreach (var cl in action.CustomLabels)
        {
            string labelName = (idToName != null && idToName.TryGetValue(cl, out var resolved)) ? resolved : cl;
            items.Add($"add_label(\"{EscapeLuaString(labelName)}\")");
        }

        // Custom labels to remove: resolve ID to human-readable Name if known
        foreach (var rl in action.CustomRemoveLabels)
        {
            string labelName = (idToName != null && idToName.TryGetValue(rl, out var resolved)) ? resolved : rl;
            items.Add($"remove_label(\"{EscapeLuaString(labelName)}\")");
        }

        if (!string.IsNullOrWhiteSpace(action.Forward))
        {
            items.Add($"forward_message(\"{EscapeLuaString(action.Forward)}\")");
        }

        return items.Count == 0 ? "actions()" : $"actions({string.Join(", ", items)})";
    }

    private static string FormatCategoryAction(string category)
    {
        return category.ToUpperInvariant() switch
        {
            SystemLabels.CategoryPersonal => "Primary",
            SystemLabels.CategoryPurchases => "Purchases",
            SystemLabels.CategorySocial => "Social",
            SystemLabels.CategoryUpdates => "Updates",
            SystemLabels.CategoryForums => "Forums",
            SystemLabels.CategoryPromotions => "Promotions",
            _ => category.StartsWith("CATEGORY_", StringComparison.OrdinalIgnoreCase)
                ? category[9..].ToLowerInvariant()
                : category
        };
    }

    private static string FormatColor(string colorHex, LuaSerializerOptions options)
    {
        if (string.IsNullOrWhiteSpace(colorHex)) return "\"\"";

        if (options.PreferColorAliases)
        {
            if (string.Equals(colorHex, "#ffffff", StringComparison.OrdinalIgnoreCase)) return "\"white\"";
            if (string.Equals(colorHex, "#000000", StringComparison.OrdinalIgnoreCase)) return "\"black\"";
        }

        return $"\"{colorHex.ToLowerInvariant()}\"";
    }

    private static string Indent(int level, LuaSerializerOptions options) =>
        level <= 0 ? string.Empty : new string(' ', level * options.IndentSpaces);

    public static string EscapeLuaString(string? value)
    {
        if (string.IsNullOrEmpty(value)) return string.Empty;
        var sb = new StringBuilder(value.Length + 4);
        foreach (char c in value)
        {
            switch (c)
            {
                case '\\': sb.Append(@"\\"); break;
                case '"': sb.Append(@"\"""); break;
                case '\n': sb.Append(@"\n"); break;
                case '\r': sb.Append(@"\r"); break;
                case '\t': sb.Append(@"\t"); break;
                default:
                    if (char.IsControl(c))
                    {
                        sb.Append($"\\{(int)c:D3}");
                    }
                    else
                    {
                        sb.Append(c);
                    }
                    break;
            }
        }
        return sb.ToString();
    }
